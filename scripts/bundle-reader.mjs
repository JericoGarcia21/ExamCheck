import { readFile, writeFile } from 'node:fs/promises'

// Git may check out CRLF on Windows; bundles compare source content, not EOLs.
const readText = async (url) => (await readFile(url, 'utf8')).replace(/\r\n/g, '\n')

const base = new URL('../', import.meta.url)
const validation = await readText(new URL('supabase/functions/_shared/validation.ts', base))
const modelUsage = await readText(new URL('supabase/functions/_shared/modelUsage.ts', base))
const entry = await readText(new URL('supabase/functions/read-answers/index.ts', base))
const sharedImport = "import { validateReadRequest, validateRecognition } from '../_shared/validation.ts'"
if (!entry.startsWith(sharedImport)) throw new Error('Unexpected reader import. Update the bundle script before deployment.')
const handler = entry.slice(sharedImport.length).trimStart().replace(/^import \{ trackedModelFetch \} from '\.\.\/_shared\/modelUsage.ts'\r?\n/, '').trimStart()
if (/^import\s/m.test(validation + handler)) throw new Error('Dashboard bundle must include all dependencies.')
const bundle = '// Generated by npm run bundle:reader. Edit index.ts or _shared/validation.ts, then regenerate.\n' +
  '// Paste this entire file into the Supabase dashboard editor as index.ts.\n\n' + validation.trimEnd() + '\n\n' + modelUsage.trimEnd() + '\n\n' + handler
const output = new URL('supabase/functions/read-answers/dashboard.ts', base)
if (process.argv.includes('--check')) {
  if (await readText(output) !== bundle) throw new Error('Dashboard bundle is stale. Run npm run bundle:reader.')
  console.log('Dashboard reader bundle is current and self-contained.')
} else {
  await writeFile(output, bundle)
  console.log('Generated supabase/functions/read-answers/dashboard.ts')
}

const guestEntry = await readText(new URL('supabase/functions/quick-check/index.ts', base))
const guestValidation = await readText(new URL('supabase/functions/_shared/quickCheck.ts', base))
const guestHandler = guestEntry.replace(/^import .*\r?\n/gm, '').trimStart()
const guestBundle = '// Generated by npm run bundle:reader. Do not edit this file directly.\n' +
  validation.trimEnd() + '\n\n' + guestValidation.trimEnd() + '\n\n' + modelUsage.trimEnd() + '\n\n' + guestHandler
const guestOutput = new URL('supabase/functions/quick-check/dashboard.ts', base)
if (process.argv.includes('--check')) {
  if (await readText(guestOutput) !== guestBundle) throw new Error('Quick Check dashboard bundle is stale. Run npm run bundle:reader.')
  console.log('Quick Check dashboard bundle is current.')
} else {
  await writeFile(guestOutput, guestBundle)
  console.log('Generated supabase/functions/quick-check/dashboard.ts')
}
